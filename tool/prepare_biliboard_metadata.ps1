$ErrorActionPreference = 'Stop'

$repoRoot = Split-Path -Parent $PSScriptRoot
$output = Join-Path $repoRoot 'lib\data\biliboard_song_metadata.g.dart'
$archiveRoot = 'https://cdn.jsdelivr.net/gh/VincentZyuApps/billboard-data@main/data/bilibili/'
$index = Invoke-RestMethod -Uri ($archiveRoot + 'index.json') -TimeoutSec 30

$archiveItems = $index.issues | ForEach-Object -Parallel {
  try {
    $payload = Invoke-RestMethod -Uri ($using:archiveRoot + $_.path) -TimeoutSec 30
    @($payload.items)
  } catch {
    @()
  }
} -ThrottleLimit 8

$targetBvids = @(
  $archiveItems |
    Where-Object { $_.bvid } |
    ForEach-Object { [string]$_.bvid } |
    Sort-Object -Unique
)

$firstPage = Invoke-RestMethod -Uri 'https://biliboard.uk/api/public/songs?page=1&per_page=100&include_history=false' -TimeoutSec 30
$pageCount = [Math]::Ceiling($firstPage.total / 100)
$pages = 1..$pageCount | ForEach-Object -Parallel {
  $target = [System.Collections.Generic.HashSet[string]]::new(
    [string[]]$using:targetBvids
  )
  for ($attempt = 1; $attempt -le 3; $attempt++) {
    try {
      $page = Invoke-RestMethod -Uri "https://biliboard.uk/api/public/songs?page=$_&per_page=100&include_history=false" -TimeoutSec 30
      return @($page.data | Where-Object { $target.Contains([string]$_.bvid) })
    } catch {
      if ($attempt -eq 3) { return @() }
    }
  }
} -ThrottleLimit 8

$songs = @($firstPage.data) + @($pages) |
  Where-Object { $_.bvid -and ($targetBvids -contains [string]$_.bvid) } |
  Group-Object bvid |
  ForEach-Object { $_.Group[0] } |
  Sort-Object bvid

function DartString([string]$value) {
  if ($null -eq $value) { $value = '' }
  return (ConvertTo-Json -InputObject $value -Compress).Replace('$', '\$')
}

$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add('// Generated by tool/prepare_biliboard_metadata.ps1. Do not edit.')
$lines.Add('const Map<String, List<String>> biliboardSongMetadata =')
$lines.Add('    <String, List<String>>{')
foreach ($song in $songs) {
  $producer = @($song.producers | ForEach-Object { $_.name }) -join ' / '
  $lines.Add(
    "  $(DartString ([string]$song.bvid)): <String>[$(DartString ([string]$song.title)), $(DartString ([string]$song.title_cn)), $(DartString $producer)],"
  )
}
$lines.Add('};')
[System.IO.File]::WriteAllLines($output, $lines, [System.Text.UTF8Encoding]::new($false))

Write-Output "Wrote $($songs.Count) / $($targetBvids.Count) archived songs to $output"
